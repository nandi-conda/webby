#!/usr/bin/env python3
"""Regenerates nim/src/icondata.nim: the Material Icons glyphs the Nim front end draws, taken from the same font
and codepoints the Flutter app uses (Icons.* in flutter/lib/src/material/icons.dart, MaterialIcons-Regular.otf),
so both front ends show the same icons.

Usage: python3 scripts/material_icons.py <flutter-sdk>   (needs fontTools: pip install fonttools)

The glyphs are Google's Material Icons, licensed under the Apache License 2.0 (as published in
github.com/google/material-design-icons; the Flutter SDK ships the font under CC BY 4.0).
"""
import pathlib
import re
import sys

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

# Every Icons.* name the Nim UI uses. Add a name here and rerun to make icon("name") available.
NAMES = """
account_circle add arrow_back arrow_forward block bookmarks bookmarks_outlined close cloud_off computer
cookie_outlined copy create_new_folder_outlined delete_outline delete_sweep_outlined edit_outlined folder_open
folder_outlined
help_outline history info_outline install_desktop key key_outlined keyboard_arrow_down keyboard_arrow_up language layers
layers_outlined
location_on_outlined lock_open lock_outline mic_none more_vert move_to_inbox_outlined notifications_outlined
open_in_browser open_in_new person_outline public refresh search send smartphone star star_border summarize
summarize_outlined tab tune visibility visibility_off visibility_off_outlined
""".split()


def main(sdk: str) -> None:
    sdk_path = pathlib.Path(sdk)
    dart = (sdk_path / "packages/flutter/lib/src/material/icons.dart").read_text()
    font = TTFont(sdk_path / "bin/cache/artifacts/material_fonts/MaterialIcons-Regular.otf")
    em = font["head"].unitsPerEm
    cmap = font.getBestCmap()
    glyphs = font.getGlyphSet()
    out = [
        "## Generated by scripts/material_icons.py from the Flutter SDK's MaterialIcons-Regular.otf; do not edit.",
        "## Material Icons by Google, Apache License 2.0. Each path is in a 0..iconEm square, y pointing down.",
        "",
        "import std/tables",
        "",
        f"const iconEm* = {em}",
        "",
        "const iconPaths* = {",
    ]
    for name in sorted(NAMES):
        m = re.search(r"static const IconData " + re.escape(name) + r"\s*=\s*IconData\(\s*(0x[0-9a-fA-F]+)", dart)
        if not m:
            sys.exit(f"Icons.{name} not found in icons.dart")
        pen = SVGPathPen(glyphs)
        # Font units have y up from the baseline; the icon square is 0..em with y down.
        glyphs[cmap[int(m.group(1), 16)]].draw(TransformPen(pen, (1, 0, 0, -1, 0, font["hhea"].ascent)))
        out.append(f'  "{name}": "{pen.getCommands()}",')
    out.append("}.toTable")
    target = pathlib.Path(__file__).resolve().parent.parent / "nim/src/icondata.nim"
    target.write_text("\n".join(out) + "\n")
    print(f"wrote {len(NAMES)} icons to {target}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "flutter")
