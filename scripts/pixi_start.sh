#!/usr/bin/env bash
# Runs the app inside the pixi environment against third_party/webby-prebuilt (see scripts/pixi_fetch.sh).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
export PATH="$ROOT/third_party/flutter/bin:$PATH"
export WEBBY_LADYBIRD_PREFIX="${WEBBY_LADYBIRD_PREFIX:-$ROOT/third_party/webby-prebuilt}"

# Flutter's Linux build uses the pixi env's clang, lld and GTK; the rpath lets the runner find that GTK at run time.
# libflutter_linux_gtk.so has no rpath of its own, so the runner also links its other two deps (epoxy, fontconfig)
# to have them loaded from the pixi env as well.
export CC=clang CXX=clang++
export LDFLAGS="-fuse-ld=lld -L$CONDA_PREFIX/lib -Wl,-rpath,$CONDA_PREFIX/lib \
  -Wl,--push-state,--no-as-needed -lepoxy -lfontconfig -Wl,--pop-state ${LDFLAGS:-}"

# WebContent aborts when fontconfig finds no fonts at all (it VERIFYs a default monospace font), which is what happens
# on systems without /etc/fonts/fonts.conf (e.g. NixOS): the prebuilt's fontconfig only looks there. So point
# fontconfig at a config that keeps the system's setup when there is one, falls back to the pixi env's otherwise, and
# always adds the env's DejaVu fonts plus the usual system and NixOS font directories.
if [ -z "${FONTCONFIG_FILE:-}" ]; then
  base_conf=/etc/fonts/fonts.conf
  [ -r "$base_conf" ] || base_conf="$CONDA_PREFIX/etc/fonts/fonts.conf"
  mkdir -p "$ROOT/third_party/fontconfig"
  export FONTCONFIG_FILE="$ROOT/third_party/fontconfig/fonts.conf"
  cat >"$FONTCONFIG_FILE" <<CONF
<?xml version="1.0"?>
<!DOCTYPE fontconfig SYSTEM "urn:fontconfig:fonts.dtd">
<!-- Generated by scripts/pixi_start.sh. -->
<fontconfig>
  <include ignore_missing="yes">$base_conf</include>
  <dir>$CONDA_PREFIX/fonts</dir>
  <dir>/usr/share/fonts</dir>
  <dir>/usr/local/share/fonts</dir>
  <dir>/run/current-system/sw/share/X11/fonts</dir>
  <dir>/etc/profiles/per-user/${USER:-$(id -un)}/share/fonts</dir>
  <dir prefix="xdg">fonts</dir>
  <dir>~/.fonts</dir>
  <dir>~/.nix-profile/share/fonts</dir>
  <cachedir prefix="xdg">fontconfig</cachedir>
</fontconfig>
CONF
fi

flutter config --no-analytics --enable-linux-desktop >/dev/null
exec "$ROOT/scripts/run_app.sh" "$@"
